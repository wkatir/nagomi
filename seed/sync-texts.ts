// For a database that already has data (seed.sql only inserts). Safe to run again.
// Run: bun seed/sync-texts.ts, then
//   bunx wrangler d1 execute DB --local --file=./seed/sync-texts.sql
// Remote only with an explicit "deploy" from Wilmer (app/README.md, "Production").
import { readFileSync, writeFileSync } from 'node:fs'
import { join } from 'node:path'
import { LOCALES } from '../src/db/schema'
import { readLanding } from './landing'
import { lit } from './sql'

const dir = import.meta.dir
const catalog = JSON.parse(readFileSync(join(dir, 'catalog.json'), 'utf8')) as {
  settings: { foundingYear: number | null }
  concerns: { slug: string }[]
  categories: { slug: string }[]
  routines: { slug: string }[]
}
const landing = readLanding({
  concerns: catalog.concerns.map((c) => c.slug),
  categories: catalog.categories.map((c) => c.slug),
  routines: catalog.routines.map((r) => r.slug),
})

const pageTexts = (table: 'concern' | 'category', texts: typeof landing.concerns) =>
  Object.entries(texts).flatMap(([slug, perLocale]) =>
    LOCALES.map((locale) => {
      const t = perLocale[locale]!
      return `UPDATE ${table}_translations SET description = ${lit(t.description)}, seo_title = ${lit(t.seoTitle)}, seo_description = ${lit(t.seoDescription)} WHERE locale = ${lit(locale)} AND ${table}_id = (SELECT id FROM ${table === 'concern' ? 'concerns' : 'categories'} WHERE slug = ${lit(slug)});`
    }),
  )

const statements = [
  '-- Generated by seed/sync-texts.ts. Do not edit by hand.',
  ...pageTexts('concern', landing.concerns),
  ...pageTexts('category', landing.categories),
  ...Object.entries(landing.routines).map(([routine, concern]) => `UPDATE routines SET concern_id = (SELECT id FROM concerns WHERE slug = ${lit(concern)}) WHERE slug = ${lit(routine)};`),
  ...(catalog.settings.foundingYear === null ? [] : [`UPDATE store_settings SET founding_year = ${lit(catalog.settings.foundingYear)} WHERE id = 1 AND founding_year IS NULL;`]),
]

writeFileSync(join(dir, 'sync-texts.sql'), `${statements.join('\n')}\n`)
console.log(`sync-texts.sql written: ${statements.length - 1} statements`)
