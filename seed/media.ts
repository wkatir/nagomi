import { spawnSync } from 'node:child_process'
import { readFileSync, writeFileSync } from 'node:fs'
import { join } from 'node:path'
import { LOCALES } from '../src/db/schema'
import { isStorePath } from '../src/lib/store-path'
import { seedPhotos } from './images'
import { lit } from './sql'

const args = process.argv.slice(2)
if (args.includes('--local') === args.includes('--remote')) {
  console.error('Pass exactly one of --local or --remote.')
  process.exit(1)
}

const dir = import.meta.dir
const config = JSON.parse(readFileSync(join(dir, '../wrangler.jsonc'), 'utf8')) as { r2_buckets: { binding: string; bucket_name: string }[] }
const bucket = config.r2_buckets.find((b) => b.binding === 'MEDIA')?.bucket_name
if (!bucket) throw new Error('wrangler.jsonc has no R2 bucket bound as MEDIA')

type SlideText = { title: string; body: string | null; ctaLabel: string | null }
type Home = { slides: { image: string; mobileImage?: string; linkPath: string; es: SlideText; en: SlideText }[] }
type Catalog = { products: { slug: string; sku: string; es: { name: string }; en: { name: string } }[] }
type Collections = { slug: string; cover?: string }[]

const readJson = <T,>(file: string): T => JSON.parse(readFileSync(join(dir, file), 'utf8'))
const catalog = readJson<Catalog>('catalog.json')
const home = readJson<Home>('home.json')
const collections = readJson<Collections>('collections.json')

const badLink = home.slides.find((s) => !isStorePath(s.linkPath))
if (badLink) throw new Error(`Slide link ${badLink.linkPath} is not a storefront path`)

const { catalog: photos, editorial } = await seedPhotos(catalog.products)
const files = [...new Map([...photos, ...editorial].map((f) => [f.key, f])).values()]

const wrangler = (command: string[]) => spawnSync('bunx', ['wrangler', ...command, ...args], { stdio: ['ignore', 'ignore', 'inherit'], shell: process.platform === 'win32' })

for (const file of files) {
  const result = wrangler(['r2', 'object', 'put', `${bucket}/${file.key}`, `--file=${file.path}`, `--content-type=${file.contentType}`])
  if (result.status !== 0) {
    console.error(`Upload of ${file.path} failed.`)
    process.exit(result.status ?? 1)
  }
  console.log(`${file.path} -> ${file.key}`)
}

const editorialFile = (file: string) => {
  const entry = editorial.find((e) => e.file === file)
  if (!entry) throw new Error(`seed/editorial/manifest.json has no entry for ${file}`)
  return entry
}
const editorialAlt = (file: string, locale: string) => {
  const alt = editorialFile(file).alt[locale]
  if (!alt) throw new Error(`seed/editorial/manifest.json has no ${locale} alt text for ${file}`)
  return alt
}
const fileId = (key: string) => `(SELECT id FROM media_files WHERE r2_key = ${lit(key)})`
const mediaId = (file: string) => fileId(editorialFile(file).key)
const productId = (index: number) => `(SELECT id FROM products WHERE slug = ${lit(catalog.products[index - 1]!.slug)})`

const statements = [
  '-- Generated by seed/media.ts. Do not edit by hand.',
  ...files.map((f) => `INSERT INTO media_files (r2_key, content_type, byte_size, width, height) VALUES (${lit(f.key)}, ${lit(f.contentType)}, ${f.byteSize}, ${f.width}, ${f.height}) ON CONFLICT (r2_key) DO NOTHING;`),
  ...photos.flatMap((ph) => {
    const image = `(SELECT id FROM product_images WHERE product_id = ${productId(ph.productId)} AND media_file_id = ${fileId(ph.key)})`
    return [
      `INSERT INTO product_images (product_id, media_file_id, kind, position) SELECT ${productId(ph.productId)}, ${fileId(ph.key)}, ${lit(ph.kind)}, ${ph.position} WHERE NOT EXISTS (SELECT 1 FROM product_images WHERE product_id = ${productId(ph.productId)} AND media_file_id = ${fileId(ph.key)});`,
      ...LOCALES.map((l) => {
        const alt = ph.alt[l]
        if (!alt) throw new Error(`No ${l} alt text for ${ph.file}`)
        return `INSERT INTO product_image_translations (image_id, locale, alt) SELECT ${image}, ${lit(l)}, ${lit(alt)} WHERE NOT EXISTS (SELECT 1 FROM product_image_translations WHERE image_id = ${image} AND locale = ${lit(l)});`
      }),
    ]
  }),
  ...home.slides.flatMap((s, i) => {
    const slide = `(SELECT id FROM home_slides WHERE position = ${i} AND desktop_media_id = ${mediaId(s.image)} AND link_path = ${lit(s.linkPath)})`
    return [
      `INSERT INTO home_slides (status, position, desktop_media_id, mobile_media_id, link_path) SELECT 'published', ${i}, ${mediaId(s.image)}, ${s.mobileImage ? mediaId(s.mobileImage) : 'NULL'}, ${lit(s.linkPath)} WHERE NOT EXISTS (SELECT 1 FROM home_slides WHERE position = ${i} AND desktop_media_id = ${mediaId(s.image)} AND link_path = ${lit(s.linkPath)});`,
      ...LOCALES.map((l) => `INSERT INTO home_slide_translations (slide_id, locale, title, body, cta_label, image_alt) SELECT ${slide}, ${lit(l)}, ${lit(s[l].title)}, ${lit(s[l].body)}, ${lit(s[l].ctaLabel)}, ${lit(editorialAlt(s.image, l))} WHERE NOT EXISTS (SELECT 1 FROM home_slide_translations WHERE slide_id = ${slide} AND locale = ${lit(l)});`),
    ]
  }),
  ...collections.flatMap((c) => {
    const cover = c.cover
    if (!cover) return []
    return [
      `UPDATE collections SET cover_media_id = ${mediaId(cover)} WHERE slug = ${lit(c.slug)};`,
      ...LOCALES.map((l) => `UPDATE collection_translations SET cover_alt = ${lit(editorialAlt(cover, l))} WHERE locale = ${lit(l)} AND collection_id = (SELECT id FROM collections WHERE slug = ${lit(c.slug)});`),
    ]
  }),
]
const sqlFile = join(dir, 'media.sql')
writeFileSync(sqlFile, `${statements.join('\n')}\n`)
const result = wrangler(['d1', 'execute', 'DB', `--file=${sqlFile}`])
if (result.status !== 0) process.exit(result.status ?? 1)
console.log(`Registered ${files.length} media files, ${photos.length} product photos, ${home.slides.length} slides`)
